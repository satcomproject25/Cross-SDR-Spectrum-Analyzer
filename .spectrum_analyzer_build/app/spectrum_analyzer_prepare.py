def _win_build_root() -> Path:
    """
    Return a short, guaranteed-space-free build root on Windows.

    The NSIS installer /D= flag silently fails (exit code 2) when the install
    path contains spaces, or when Python passes it as a quoted shell token.
    We avoid both by keeping all Windows build artefacts under
    %USERPROFILE%\\fa_build -- a short path with no spaces.
    """
    return Path(os.environ.get("USERPROFILE", "C:\\")) / "fa_build"


def _ensure_mamba(work: Path, mf_installer: Path, target_os: str) -> Path:
    """
    Install a temporary Miniforge and return the path to the mamba binary.

    Windows notes
    -------------
    The Miniforge .exe is an NSIS installer with two strict rules:
      1. /D= must be the VERY LAST argument on the command line.
      2. The path after /D= must NOT be quoted (even with spaces).
    Python subprocess list-form automatically quotes arguments, triggering
    exit code 2.  We fix this two ways:
      a. shell=True so the command string reaches NSIS verbatim.
      b. tmp_conda lives under %USERPROFILE%\\fa_build\\tmp_conda -
         guaranteed no spaces, regardless of where the project folder is.
    """
    if target_os == "windows":
        # Short, space-free path regardless of where the project lives
        tmp_conda = _win_build_root() / "tmp_conda"
    else:
        tmp_conda = work / "tmp_conda"

    if not tmp_conda.exists():
        info("Bootstrapping temporary Miniforge for package operations...")
        tmp_conda.parent.mkdir(parents=True, exist_ok=True)

        if target_os == "windows":
            # Use shell=True + raw string so Python never quotes the /D= path
            install_cmd = (
                f'"{mf_installer}" /S /InstallationType=JustMe '
                f'/RegisterPython=0 /D={tmp_conda}'
            )
            info(f"  Running: {install_cmd}")
            result = subprocess.run(install_cmd, shell=True)
            if result.returncode not in (0, 3010):  # 3010 = reboot needed (harmless)
                die(
                    f"Miniforge installer failed (exit code {result.returncode}).\n"
                    f"  Install path tried: {tmp_conda}\n"
                    f"  Ensure the path exists and contains no spaces."
                )
        else:
            run_cmd(["bash", str(mf_installer), "-b", "-p", str(tmp_conda), "-f"])

        ok(f"Temporary Miniforge at {tmp_conda}")
    else:
        warn(f"Temporary Miniforge already exists at {tmp_conda}, skipping")

    if target_os == "windows":
        mamba = tmp_conda / "Scripts" / "mamba.exe"
    else:
        mamba = tmp_conda / "bin" / "mamba"

    if not mamba.exists():
        die(
            f"mamba not found at {mamba}\n"
            f"  The Miniforge installation likely failed silently.\n"
            f"  Delete {tmp_conda} and run the script again."
        )

    # Ensure conda-pack is available in the temporary base env
    info("Ensuring conda-pack is in the temporary base environment...")
    run_cmd([str(mamba), "install", "-y", "-n", "base",
             "-c", "conda-forge", "conda-pack", "--quiet"])
    return mamba


