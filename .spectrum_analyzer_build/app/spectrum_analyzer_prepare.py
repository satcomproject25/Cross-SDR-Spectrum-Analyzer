#!/usr/bin/env python3
"""
spectrum_analyzer_prepare.py
=======================
Single-file bundle builder.  Run ONCE on any internet-connected machine.
Produces a ZIP that installs Spectrum Analyzer on a fully offline machine with
NO pre-installed Python, conda, or internet access on the target.

Requirements (build machine only):
    Python 3.7+  --  standard library only, no pip installs needed

Usage:
    python spectrum_analyzer_prepare.py
    python spectrum_analyzer_prepare.py --arch aarch64    # for Raspberry Pi 4/5
    python spectrum_analyzer_prepare.py --clean           # fresh build

What it downloads:
    * Miniforge3 installer  (.sh on Linux, .exe on Windows)
    * All conda packages    (SoapySDR, HackRF driver, PyQt6, scipy, ...)
    * All pip wheels        (FastAPI, uvicorn, websockets, ...)
    * Your application source code

Output:
    spectrum_analyzer_bundle_linux_x86_64.zip   (built on Linux)
    spectrum_analyzer_bundle_linux_aarch64.zip  (built on Linux, --arch aarch64)
    spectrum_analyzer_bundle_windows_x86_64.zip (built on Windows)

On the offline target machine:
    Linux   ->  unzip spectrum_analyzer_bundle_*.zip  &&  bash install.sh
    Windows ->  Unzip  ->  double-click install.bat
                       OR right-click install.ps1 -> "Run with PowerShell"

NOTE: The bundle is platform-specific because conda environments contain
compiled native code.  Build on Linux to deploy on Linux/Pi; build on
Windows to deploy on Windows.
"""

