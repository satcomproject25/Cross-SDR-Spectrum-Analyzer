# -- Unicode -> ASCII sanitiser for embedded script templates -----------------
# PowerShell and bash both fail on box-drawing / dash Unicode characters when
# the file encoding is not declared.  Replace every non-ASCII char with a safe
# ASCII equivalent before writing templates into the ZIP.
_UNICODE_MAP = str.maketrans({
    '\u2014': '-',   # em dash        -
    '\u2013': '-',   # en dash        -
    '\u2012': '-',   # figure dash
    '\u2010': '-',   # hyphen
    '\u2500': '-',   # box light horiz -
    '\u2501': '-',   # box heavy horiz
    '\u2550': '=',   # box double horiz =
    '\u2502': '|',   # box light vert
    '\u2551': '|',   # box double vert
    '\u2018': "'",   # left single quote
    '\u2019': "'",   # right single quote
    '\u201c': '"',   # left double quote
    '\u201d': '"',   # right double quote
    '\u2026': '...', # ellipsis
    '\u00e2': '',    # garbage from bad re-encode
})

def _ascii(text: str) -> str:
    """Replace every known Unicode decoration with plain ASCII."""
    text = text.translate(_UNICODE_MAP)
    # Catch anything else above 0x7F with a fallback
    return text.encode('ascii', errors='replace').decode('ascii').replace('?', '-')

# UTF-8 BOM -- tells PowerShell the file is UTF-8, preventing misread of any
# remaining special bytes.
_UTF8_BOM = '\ufeff'

def _extract_all_drivers(tmp_env: Path, work: Path, target_os: str) -> None:
    """
    Extract Windows USB driver files for all three hardware types from the
    conda environment into drivers/<hardware>/ folders inside the bundle.

    Layout inside the zip:
        drivers/uhd/       <- USRP X300/B200  (pnputil installable)
        drivers/hackrf/    <- HackRF One       (pnputil installable)
        drivers/plutosdr/  <- PlutoSDR         (pnputil installable)

    On Linux, udev rules are written by install.sh directly (no files needed).

    Known conda env paths (Windows):
        UHD:      Library/share/uhd/usbdriver/
        HackRF:   Library/share/hackrf/        (may not exist - falls back to Zadig note)
        PlutoSDR: Library/share/libiio/        (libiio Windows driver inf files)
    """
    if target_os != "windows":
        return

    drivers_root = work / "drivers"
    drivers_root.mkdir(exist_ok=True)

    # Each entry: (subfolder_in_bundle, paths_to_try_in_env, display_name)
    driver_specs = [
        (
            "uhd",
            [
                tmp_env / "Library" / "share" / "uhd" / "usbdriver",
                tmp_env / "Library" / "uhd" / "usbdriver",
            ],
            "USRP (UHD)",
        ),
        (
            "hackrf",
            [
                tmp_env / "Library" / "share" / "hackrf",
                tmp_env / "Library" / "drivers" / "hackrf",
                tmp_env / "Library" / "share" / "libhackrf",
            ],
            "HackRF One",
        ),
        (
            "plutosdr",
            [
                tmp_env / "Library" / "share" / "libiio",
                tmp_env / "Library" / "share" / "ad9361",
                tmp_env / "Library" / "drivers" / "libiio",
            ],
            "PlutoSDR (libiio)",
        ),
    ]

    for subfolder, search_paths, display_name in driver_specs:
        dst = drivers_root / subfolder
        found_src = None
        for candidate in search_paths:
            if candidate.exists() and list(candidate.rglob("*.inf")):
                found_src = candidate
                break

        if found_src is None:
            warn(f"{display_name}: driver .inf files not found in conda env")
            warn(f"  Searched: {[str(p) for p in search_paths]}")
            warn(f"  Users will be directed to install manually.")
            # Create empty marker so install_drivers.ps1 shows the fallback URL
            dst.mkdir(exist_ok=True)
            dst.mkdir(exist_ok=True)
            note = display_name + " driver files not found. Install from vendor website."
            (dst / "NOT_FOUND.txt").write_text(note)
        else:
            if dst.exists():
                shutil.rmtree(dst)
            shutil.copytree(found_src, dst)
            inf_count = len(list(dst.rglob("*.inf")))
            ok(f"{display_name}: {inf_count} .inf files -> drivers/{subfolder}/")


def cmd_prepare(args) -> None:
    target_os = "windows" if sys.platform == "win32" else "linux"
    arch      = args.arch
    work      = Path(args.workdir).resolve()
    out_zip   = Path(args.outdir).resolve() / f"spectrum_analyzer_bundle_{target_os}_{arch}.zip"

    section(f"PREPARE -- building offline bundle for {target_os}/{arch}")
    info(f"Build workspace : {work}")
    info(f"Output archive  : {out_zip}")

    if args.clean and work.exists():
        warn(f"--clean: removing {work}")
        shutil.rmtree(work)

    work.mkdir(parents=True, exist_ok=True)
    (work / "pip_wheels").mkdir(exist_ok=True)

    # -- Step 1: Download Miniforge installer ---------------------------------
    section("Step 1/5 -- Downloading Miniforge installer")
    url, mf_name = _miniforge_url(target_os, arch)
    mf_path = work / mf_name
    if not mf_path.exists():
        download(url, mf_path, mf_name)
    else:
        warn(f"Already present: {mf_name}")

    # -- Step 2: Bootstrap temporary conda + create environment ---------------
    section("Step 2/5 -- Creating conda environment")
    mamba = _ensure_mamba(work, mf_path, target_os)

    # On Windows, keep tmp_env under the space-free fa_build root
    if target_os == "windows":
        tmp_env = _win_build_root() / "tmp_env"
    else:
        tmp_env = work / "tmp_env"
    if tmp_env.exists():
        warn("Removing existing tmp_env for clean build...")
        shutil.rmtree(tmp_env)

    info("Creating conda environment (resolving all packages -- 5-15 min)...")
    run_cmd([str(mamba), "create", "-y",
             "--prefix", str(tmp_env),
             *CONDA_CHANNELS,
             *CONDA_PACKAGES])
    ok("Conda environment created")

    # -- Step 2b: Extract UHD driver files for offline Windows installation
    _extract_all_drivers(tmp_env, work, target_os)

    # -- Step 3: Download pip wheels ------------------------------------------
    section("Step 3/5 -- Downloading pip wheels")
    if target_os == "windows":
        pip_exe = tmp_env / "Scripts" / "pip.exe"
    else:
        pip_exe = tmp_env / "bin" / "pip"

    run_cmd([str(pip_exe), "download",
             "--dest", str(work / "pip_wheels"),
             "--prefer-binary",
             *PIP_PACKAGES])
    ok("Pip wheels downloaded")

    # -- Step 4: conda-pack the environment -----------------------------------
    section("Step 4/5 -- Packing conda environment (3-10 min)")
    # Keep the packed env in the same space-free directory as tmp_env
    if target_os == "windows":
        packed_env = _win_build_root() / "spectrum_analyzer_env.tar.gz"
    else:
        packed_env = work / "spectrum_analyzer_env.tar.gz"
    if target_os == "windows":
        conda_pack_exe = _win_build_root() / "tmp_conda" / "Scripts" / "conda-pack.exe"
    else:
        conda_pack_exe = work / "tmp_conda" / "bin" / "conda-pack"

    run_cmd([str(conda_pack_exe),
             "--prefix", str(tmp_env),
             "--output", str(packed_env),
             "--force"])
    ok(f"Environment packed: {packed_env.stat().st_size >> 20} MB")

    # -- Step 5: Copy app source -----------------------------------------------
    section("Step 5/5 -- Copying application source")
    app_dest = work / "app"
    if app_dest.exists():
        shutil.rmtree(app_dest)
    # Exclude files that should not be in the bundle
    EXCLUDE = {
        ".git", "__pycache__", ".pytest_cache",
        "*.pyc", "*.pyo", "*.egg-info",
        args.workdir,                    # don't bundle the build workspace
        out_zip.name,
    }

    def _ignore(directory, contents):
        ignored = set()
        for item in contents:
            if item in EXCLUDE:
                ignored.add(item)
            if any(item.endswith(e.lstrip("*")) for e in EXCLUDE if e.startswith("*")):
                ignored.add(item)
        return ignored

    shutil.copytree(APP_SOURCE_DIR, app_dest, ignore=_ignore,
                    ignore_dangling_symlinks=True)
    # Remove this prepare script from the app copy
    for f in app_dest.glob("Spectrum_Analyzer.py"):
        f.unlink()
    ok(f"Application source copied ({sum(1 for _ in app_dest.rglob('*'))} files)")

    # -- Assemble the ZIP ------------------------------------------------------
    section("Assembling bundle ZIP")
    info(f"Output: {out_zip}")

    out_zip.parent.mkdir(parents=True, exist_ok=True)

    with zipfile.ZipFile(out_zip, "w", zipfile.ZIP_DEFLATED,
                         compresslevel=6) as zf:

        def _add(src: Path, arc_name: str) -> None:
            zf.write(src, arc_name)

        def _add_str(content: str, arc_name: str, mode: int = 0o644) -> None:
            info_obj = zipfile.ZipInfo(arc_name)
            info_obj.external_attr = (mode << 16)
            info_obj.compress_type = zipfile.ZIP_DEFLATED
            zf.writestr(info_obj, content)

        # Miniforge installer
        _add(mf_path, mf_name)
        info(f"  + {mf_name}")

        # Packed conda environment
        _add(packed_env, "spectrum_analyzer_env.tar.gz")
        info("  + spectrum_analyzer_env.tar.gz")

        # Pip wheels
        wheel_count = 0
        for whl in (work / "pip_wheels").iterdir():
            _add(whl, f"pip_wheels/{whl.name}")
            wheel_count += 1
        info(f"  + pip_wheels/  ({wheel_count} wheels)")

        # Hardware driver files (Windows only -- drivers/uhd/, /hackrf/, /plutosdr/)
        drivers_root = work / "drivers"
        if drivers_root.exists():
            drv_total = 0
            for hw_dir in sorted(drivers_root.iterdir()):
                if hw_dir.is_dir():
                    hw_count = 0
                    for f in hw_dir.rglob("*"):
                        if f.is_file():
                            arc = "drivers/" + hw_dir.name + "/" + str(f.relative_to(hw_dir)).replace(os.sep, "/")
                            _add(f, arc)
                            hw_count += 1
                    info(f"  + drivers/{hw_dir.name}/  ({hw_count} files)")
                    drv_total += hw_count
            info(f"  + drivers/  total {drv_total} files across {sum(1 for d in drivers_root.iterdir() if d.is_dir())} hardware types")

        # Application source
        file_count = 0
        for src in app_dest.rglob("*"):
            if src.is_file():
                arc = "app/" + str(src.relative_to(app_dest)).replace(os.sep, "/")
                _add(src, arc)
                file_count += 1
        info(f"  + app/  ({file_count} files)")

        # Installer scripts
        _add_str(_ascii(INSTALL_SH),    "install.sh",          mode=0o755)
        _add_str(_ascii(UNINSTALL_SH),  "uninstall.sh",        mode=0o755)
        _add_str(_ascii(CHECK_SH),      "check.sh",            mode=0o755)
        _add_str(_UTF8_BOM + _ascii(INSTALL_PS1),          "install.ps1",         mode=0o644)
        _add_str(_UTF8_BOM + _ascii(DRIVER_MENU_PS1),      "install_drivers.ps1", mode=0o644)
        _add_str(_UTF8_BOM + _ascii(UNINSTALL_PS1),        "uninstall.ps1",       mode=0o644)
        _add_str(_ascii(INSTALL_BAT),                       "install.bat",         mode=0o644)
        _add_str(_ascii(INSTALL_DRIVERS_BAT),               "install_drivers.bat", mode=0o644)
        _add_str(_ascii(UNINSTALL_BAT),                     "uninstall.bat",       mode=0o644)
        _add_str(_UTF8_BOM + _ascii(CHECK_PS1),             "check.ps1",           mode=0o644)
        _add_str(_ascii(CHECK_BAT),                         "check.bat",           mode=0o644)
        _add_str(_readme(target_os, arch), "README.txt", mode=0o644)
        info("  + install / uninstall / driver scripts added to bundle")
        info("  + install.sh / install.ps1 / install.bat / README.txt")

    size_mb = out_zip.stat().st_size >> 20
    ok("")
    ok("=" * 62)
    ok(f" Bundle ready: {out_zip.name}")
    ok(f" Size:         {size_mb} MB")
    ok("=" * 62)

    print()
    info("Transfer to the offline machine (USB drive, scp, etc.):")
    info(f"  {out_zip.name}")
    print()
    info("On the offline machine:")
    if target_os == "linux":
        info(f"  unzip {out_zip.name}")
        info("  cd spectrum_analyzer_bundle")
        info("  bash install.sh")
        print()
        info("After install (new terminal):")
        info("  spectrum_analyzer               # GUI")
        info("  spectrum_analyzer --headless    # web-only")
    else:
        info(f"  Unzip {out_zip.name}")
        info("  Double-click install.bat")
        info("     -- or -")
        info("  Right-click install.ps1 -> 'Run with PowerShell'")


