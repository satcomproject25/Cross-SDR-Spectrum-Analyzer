def cmd_status() -> None:
    section("SpectrumAnalyzer — Installation Status")
    is_win = sys.platform == "win32"
    home   = Path.home()

    if is_win:
        conda_dir   = home / "miniforge3"
        env_dir     = conda_dir / "envs" / ENV_NAME
        install_dir = home / APP_NAME
        launcher    = install_dir / "run_app.bat"
    else:
        conda_dir   = home / "miniforge3"
        env_dir     = conda_dir / "envs" / ENV_NAME
        install_dir = home / APP_NAME
        launcher    = home / ".local" / "bin" / APP_NAME

    G = "\033[0;32m✓\033[0m"
    B = "\033[0;31m✗\033[0m"

    def chk(label, path):
        mark = G if Path(path).exists() else B
        print(f"  {mark}  {label:40s} {path}")

    chk("Miniforge",             conda_dir)
    chk(f"Conda env '{ENV_NAME}'", env_dir)
    chk("Application (run.py)", install_dir / "run.py")
    chk("Launcher",              launcher)

    python = env_dir / ("python.exe" if is_win else "bin/python")
    if python.exists():
        print()
        print("Python packages:")
        packages = [
            ("numpy",      "numpy"),
            ("scipy",      "scipy"),
            ("PyQt6",      "PyQt6.QtCore"),
            ("pyqtgraph",  "pyqtgraph"),
            ("SoapySDR",   "SoapySDR"),
            ("fastapi",    "fastapi"),
            ("uvicorn",    "uvicorn"),
            ("websockets", "websockets"),
        ]
        check_code = (
            "import importlib, sys\n"
            "pkgs=" + repr(packages) + "\n"
            "for label, mod in pkgs:\n"
            "    try:\n"
            "        m=importlib.import_module(mod)\n"
            "        print(f'  \\033[0;32m✓\\033[0m  {label:<18} {getattr(m,\"__version__\",\"ok\")}')\n"
            "    except ImportError:\n"
            "        print(f'  \\033[0;31m✗\\033[0m  {label:<18} NOT FOUND')\n"
        )
        subprocess.run([str(python), "-c", check_code])
    else:
        warn("Python not found in conda env — run install first")


