def main() -> None:
    host_os   = "windows" if sys.platform == "win32" else "linux"
    host_arch = "x86_64" if platform.machine() in ("x86_64", "AMD64") else "aarch64"

    parser = argparse.ArgumentParser(
        prog="SpectrumAnalyzer_prepare.py",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        description=textwrap.dedent("""\
            Build an offline installer bundle for SpectrumAnalyzer.

            Run on an internet-connected machine.  Generates a ZIP that
            installs everything on an offline target with no pre-installed
            Python, conda, or internet access.

            NOTE: Build on the SAME platform as the target machine.
              Linux x86_64 machine  → bundle for Linux x86_64 server/desktop
              Linux aarch64 machine → bundle for Raspberry Pi 4/5
              Windows machine       → bundle for Windows
        """),
        epilog=textwrap.dedent("""\
            Examples:
              python SpectrumAnalyzer_prepare.py
              python SpectrumAnalyzer_prepare.py --arch aarch64
              python SpectrumAnalyzer_prepare.py --clean --outdir /mnt/usb

            On offline Linux target:
              unzip SpectrumAnalyzer_bundle_linux_x86_64.zip
              bash install.sh

            On offline Windows target:
              Unzip → double-click install.bat
        """),
    )
    sub = parser.add_subparsers(dest="command")

    p_prep = sub.add_parser("prepare", help="Download all deps and build bundle zip (default)")
    p_prep.add_argument("--arch",    default=host_arch,
                        choices=["x86_64", "aarch64"],
                        help=f"Target CPU architecture (default: {host_arch})")
    p_prep.add_argument("--outdir",  default=".", metavar="DIR",
                        help="Where to write the bundle zip (default: current dir)")
    p_prep.add_argument("--workdir", default=f".SpectrumAnalyzer_build",
                        metavar="DIR", help="Build workspace directory")
    p_prep.add_argument("--clean",   action="store_true",
                        help="Remove the build workspace before starting")

    sub.add_parser("status", help="Verify an existing installation on this machine")

    args = parser.parse_args()

    # Default to 'prepare' when no subcommand given
    if args.command is None:
        # Re-parse with prepare defaults
        args = parser.parse_args(["prepare"])

    if args.command == "prepare":
        # Validate Python version
        if sys.version_info < (3, 7):
            die("Python 3.7 or newer is required.")
        # Validate required tools
        missing = []
        if host_os == "linux":
            for tool in ("bash", "tar", "curl"):
                if not shutil.which(tool):
                    missing.append(tool)
        if missing:
            die(f"Required tools not found: {', '.join(missing)}\n"
                f"  Install with: sudo apt-get install {' '.join(missing)}")
        cmd_prepare(args)

    elif args.command == "status":
        cmd_status()


if __name__ == "__main__":
    main()  